import { describe, it, expect } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtemp, writeFile, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  draftFromPages,
  extractPdf,
  type ExtractedPage,
} from "../lib/pdf-conversion";
import { textPdf, scannedPdf } from "./helpers/pdf";
import { importInput } from "../lib/validation";
const metadata = {
  examId: "synthetic",
  year: 2025,
  stage: "Test",
  shift: "Test",
  title: "Synthetic test only",
  sourceUrl: "https://example.org/test.pdf",
  checksum: "a".repeat(64),
  permissionEvidence: "Synthetic test generated by its author",
};
const page = (text: string, number = 1): ExtractedPage => ({
  page: number,
  text,
  method: "TEXT",
});
describe("automatic PDF conversion", () => {
  it("creates valid unscored drafts with original provenance and page numbers", () => {
    const result = draftFromPages(
      [
        page("Q1. Choose one\n(A) First\n(B) Second", 2),
        page("2: Choose again\na. Yes\nb. No", 3),
      ],
      metadata,
    );
    expect(result.questionCount).toBe(2);
    const payload = importInput.parse(result.payload);
    expect(payload.source.permission).toBe("PENDING");
    expect(payload.source.checksum).toBe(metadata.checksum);
    expect(
      payload.questions.map((q) => [q.sourcePage, q.answer, q.keyStatus]),
    ).toEqual([
      [2, null, "UNAVAILABLE"],
      [3, null, "UNAVAILABLE"],
    ]);
  });
  it("supports inline and wrapped options, numeric options and Hindi text", () => {
    const result = draftFromPages(
      [
        page(
          "1. सही उत्तर चुनें\n(A) पहला (B) दूसरा\n2. Wrapped question\ncontinued text\n(1) Long option\ncontinued option\n(2) Other option",
        ),
      ],
      metadata,
    );
    expect(result.payload?.questions[0].language).toBe("hi");
    expect(result.payload?.questions[1].options).toEqual([
      "Long option\ncontinued option",
      "Other option",
    ]);
  });
  it("keeps raw text and explains unsupported layouts instead of inventing questions", () => {
    const pages = [page("Unnumbered descriptive question with no MCQ answers")];
    const result = draftFromPages(pages, metadata);
    expect(result.payload).toBeNull();
    expect(result.pages).toEqual(pages);
    expect(result.warnings.join(" ")).toContain("manual");
  });
  it("flags duplicate numbering and incomplete question options", () => {
    const result = draftFromPages(
      [
        page(
          "1. First\n(A) Yes\n(B) No\n1. Duplicate\n(A) Yes\n(B) No\n2. Missing options",
        ),
      ],
      metadata,
    );
    expect(result.questionCount).toBe(1);
    expect(result.needsReview).toBe(true);
    expect(result.warnings.join(" ")).toContain("Repeated question number");
    expect(result.warnings.join(" ")).toContain("no complete MCQ option set");
  });
  it("handles inline question/options and missing OCR spaces after numbering", () => {
    const result = draftFromPages(
      [
        page(
          "1.Choose one (A) First (B) Second\n2.Which option?\n(A) Yes\n(B) No",
        ),
      ],
      metadata,
    );
    expect(result.questionCount).toBe(2);
    expect(result.payload?.questions[0].text).toBe("Choose one");
    expect(result.payload?.questions[0].options).toEqual(["First", "Second"]);
  });
  it("rejects invalid or oversized uploads", async () => {
    await expect(extractPdf(Buffer.from("not a PDF"))).rejects.toThrow(
      "Expected a PDF",
    );
    await expect(extractPdf(Buffer.alloc(20_000_001))).rejects.toThrow(
      "Expected a PDF",
    );
  });
  it("extracts a real synthetic text PDF and builds a draft", async () => {
    // A real ~20 MB document must pass both upload and worker limits.
    const pages = await extractPdf(textPdf(undefined, 19_998_000));
    expect(pages[0].method).toBe("TEXT");
    expect(draftFromPages(pages, metadata).questionCount).toBe(2);
  });
  it("OCRs an image-only PDF automatically", async () => {
    const dir = await mkdtemp(join(tmpdir(), "mindmitra-scan-test-"));
    try {
      await writeFile(join(dir, "text.pdf"), textPdf());
      execFileSync("pdftoppm", [
        "-singlefile",
        "-scale-to",
        "1800",
        join(dir, "text.pdf"),
        join(dir, "scan"),
      ]);
      const pages = await extractPdf(
        scannedPdf(await readFile(join(dir, "scan.ppm"))),
      );
      expect(pages[0].method).toBe("OCR");
      expect(pages[0].text).toContain("Which number is even");
      expect(draftFromPages(pages, metadata).questionCount).toBe(2);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }, 60_000);
  it("returns a readable failure for a corrupt PDF", async () => {
    await expect(extractPdf(Buffer.from("%PDF-corrupt"))).rejects.toThrow(
      "could not process",
    );
  });
});
